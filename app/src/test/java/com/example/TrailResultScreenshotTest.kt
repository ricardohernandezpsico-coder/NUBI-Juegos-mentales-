/** El final de Rastro de luz con datos de ejemplo: tu rastro, por modo (el que más te costó, con texto), la lectura y un modo nuevo. */
@RunWith(RobolectricTestRunner::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
@Config(qualifiers = RobolectricDeviceQualifiers.Pixel8, sdk = [36])
class TrailResultScreenshotTest {
  @get:Rule val composeTestRule = createComposeRule()

  @Test
  fun final_de_rastro_de_luz() {
    val result = GamePlayResult(
      gameId = "secuencia", score = 74, correctAnswers = 14, totalTrials = 19, timed = true, level = 9,
      // el rastro simple: 7 rondas (mejor largo 5); al revés 4 rondas (3 bien); el cielo gira 5 (2 bien: el que más costó); en marcha 3 (2 bien)
      rasBestLen = listOf(5, 4, 3, 2), rasRounds = listOf(7, 4, 5, 3), rasHits = listOf(7, 3, 2, 2),
      rasModesSeen = 15, rasNewModes = 8
    )
    composeTestRule.setContent {
      NeuroVidaTheme {
        Box(Modifier.width(412.dp).height(915.dp).background(Color(0xFF050823))) {
          GameResultScreen(
            result = result, didLevelUp = false, isDailyFlow = true, dailyCompletedCount = 1, dailyTotalCount = 3,
            onPlayAgain = {}, onContinue = {}
          )
        }
      }
    }
    composeTestRule.onRoot().captureRoboImage(filePath = "src/test/screenshots/rastro-final.png")
    composeTestRule.onAllNodes(hasScrollAction()).onFirst().performTouchInput { swipeUp(durationMillis = 100) }
    composeTestRule.waitForIdle()
    composeTestRule.onRoot().captureRoboImage(filePath = "src/test/screenshots/rastro-final-2.png")
  }
}
